# ZETA RAYS — settings shared by bash and zsh (interactive terminal).
# shellcheck shell=bash
# Only aliases and variables: no slow commands here, the terminal must open
# instantly even on a slow computer.

# modern tools where available; the Debian names (batcat, fdfind) become the
# usual ones (bat, fd). The classic commands remain available: \ls, \cat
if command -v eza >/dev/null 2>&1; then
  alias ls='eza --group-directories-first'
  alias ll='eza -la --group-directories-first --git --time-style=long-iso'
  alias la='eza -a --group-directories-first'
  alias lt='eza --tree --level=2 --group-directories-first'
else
  alias ls='ls --color=auto --group-directories-first'
  alias ll='ls -la --color=auto'
fi
command -v batcat >/dev/null 2>&1 && alias bat='batcat'
command -v fdfind >/dev/null 2>&1 && alias fd='fdfind'
alias grep='grep --color=auto'
alias ip='ip -color=auto'
alias diff='diff --color=auto'

# less: colors, case-insensitive search, no pager if the text fits on the
# screen; lesspipe lets it read archives, PDFs, .deb packages and more
export LESS='-R -F -X -i -M'
[ -x /usr/bin/lesspipe ] && eval "$(SHELL=/bin/sh lesspipe)"
if command -v batcat >/dev/null 2>&1; then
  export BAT_THEME='ansi'
  export MANPAGER="sh -c 'col -bx | batcat -l man -p'"
  export MANROFFOPT='-c'
fi
export EDITOR="${EDITOR:-nano}"

# prompt: the user's own configuration if present, otherwise the ZETA RAYS one
# with the accent color (generated by «zeta shell»)
if [ ! -f "$HOME/.config/starship.toml" ] && [ -f "$HOME/.cache/zeta/starship.toml" ]; then
  export STARSHIP_CONFIG="$HOME/.cache/zeta/starship.toml"
fi
