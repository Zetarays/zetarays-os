"""Settings > Keyboard & Mouse.

Key repeat, pointer speed, scrolling direction, touchpad and the shortcut
that switches between keyboard layouts. Everything applies at once and
stays after logging in again:

- the choices are kept in ~/.config/zeta/input.json;
- ~/.config/hypr/zeta_input.lua is generated from them and read by
  hyprland.lua at every start ({ config = <hl.config table>, kb_switch = ...});
- the running compositor gets the same values through "hyprctl eval".

The keyboard layouts themselves are a system setting (login screen too):
they live in Language & Region, linked from here.
"""
import json
import os
import re

import gi
gi.require_version("Gtk", "4.0")
gi.require_version("Adw", "1")
from gi.repository import Adw, GLib, Gtk  # noqa: E402

from i18n import tr  # noqa: E402
from ui.page_tools import hypr_eval, lua_literal, scale_row, write_if_changed  # noqa: E402

PREFS = os.path.expanduser("~/.config/zeta/input.json")
LUA = os.path.expanduser("~/.config/hypr/zeta_input.lua")
KEYBOARD_LUA = os.path.expanduser("~/.config/hypr/zeta_keyboard.lua")
EVDEV = "/usr/share/X11/xkb/rules/evdev.lst"

# Hyprland's own defaults, except natural scrolling on touchpads (the ZETA
# RAYS default since 1.0, set in hyprland.lua)
DEFAULTS = {"repeat_delay": 600, "repeat_rate": 25, "sensitivity": 0.0, "natural_scroll": False,
            "touchpad_natural_scroll": True, "tap_to_click": True, "disable_while_typing": True,
            "switch": "grp:alt_shift_toggle"}
RANGES = {"repeat_delay": (150, 1500), "repeat_rate": (5, 80), "sensitivity": (-1.0, 1.0)}
# XKB options for switching layouts (Super + Space is the app launcher)
SWITCHES = ["grp:alt_shift_toggle", "grp:ctrl_shift_toggle", "grp:caps_toggle",
            "grp:alt_space_toggle"]


def load():
    prefs = dict(DEFAULTS)
    try:
        with open(PREFS, encoding="utf-8") as f:
            saved = json.load(f)
    except (OSError, ValueError):
        saved = {}
    if not isinstance(saved, dict):
        saved = {}
    for k, default in DEFAULTS.items():
        v = saved.get(k, default)
        if isinstance(default, bool):
            prefs[k] = v if isinstance(v, bool) else default
        elif k in RANGES:
            lo, hi = RANGES[k]
            try:
                v = type(default)(v)
            except (TypeError, ValueError):
                v = default
            prefs[k] = min(hi, max(lo, v))
        elif k == "switch":
            prefs[k] = v if v in SWITCHES else default
    return prefs


def hypr_table(prefs):
    """The hl.config() table for these choices."""
    return {"input": {
        "repeat_delay": int(prefs["repeat_delay"]), "repeat_rate": int(prefs["repeat_rate"]),
        "sensitivity": round(float(prefs["sensitivity"]), 2),
        "natural_scroll": bool(prefs["natural_scroll"]),
        "touchpad": {"natural_scroll": bool(prefs["touchpad_natural_scroll"]),
                     "tap_to_click": bool(prefs["tap_to_click"]),
                     "disable_while_typing": bool(prefs["disable_while_typing"])}}}


def lua_text(prefs):
    return ("-- Settings > Keyboard & Mouse (generated by ZETA RAYS Settings: changes made\n"
            "-- here are overwritten). Read by hyprland.lua.\n"
            "return {\n    config = %s,\n    kb_switch = %s,\n}\n"
            % (lua_literal(hypr_table(prefs)), lua_literal(prefs["switch"])))


def save(prefs):
    os.makedirs(os.path.dirname(PREFS), exist_ok=True)
    with open(PREFS + ".tmp", "w", encoding="utf-8") as f:
        json.dump(prefs, f, indent=1)
    os.replace(PREFS + ".tmp", PREFS)
    write_if_changed(LUA, lua_text(prefs))


def session_layouts():
    """(layouts, options) of this session, from the file written at login."""
    try:
        with open(KEYBOARD_LUA, encoding="utf-8") as f:
            text = f.read()
    except OSError:
        return "us", ""
    lay = re.search(r'layout\s*=\s*"([^"]*)"', text)
    opt = re.search(r'options\s*=\s*"([^"]*)"', text)
    return (lay.group(1) if lay else "us") or "us", opt.group(1) if opt else ""


def layout_names():
    """{code: description} from the XKB rules (English names)."""
    names, section = {}, ""
    try:
        with open(EVDEV, encoding="utf-8") as f:
            for line in f:
                if line.startswith("!"):
                    section = line[1:].strip()
                elif section == "layout" and line.strip():
                    code, _, desc = line.strip().partition(" ")
                    names[code] = desc.strip()
    except OSError:
        pass
    return names


def has_touchpad():
    try:
        with open("/proc/bus/input/devices", encoding="utf-8", errors="replace") as f:
            text = f.read().lower()
    except OSError:
        return False
    return "touchpad" in text or "trackpad" in text


class KeyboardMousePage(Adw.PreferencesPage):
    def __init__(self):
        super().__init__()
        self.prefs = load()
        self._timer = None

        # --- keyboards (system setting, in Language & Region)
        layouts, _options = session_layouts()
        names = layout_names()
        gk = Adw.PreferencesGroup(
            title=tr("Keyboards"),
            description=tr("The keyboard layouts are chosen in Language & Region: they apply to "
                           "the login screen too."))
        current = Adw.ActionRow(title=tr("Keyboard layouts"), use_markup=False, activatable=True,
                                subtitle=", ".join(names.get(c, c) for c in layouts.split(",")))
        current.add_suffix(Gtk.Image(icon_name="go-next-symbolic"))
        current.connect("activated", lambda *_: self._open_language())
        gk.add(current)
        labels = [tr("Alt + Shift"), tr("Ctrl + Shift"), tr("Caps Lock"), tr("Alt + Space")]
        self.switch_row = Adw.ComboRow(
            title=tr("Switch layouts with"),
            subtitle=tr("With two or more layouts. A click on the indicator in the bar also "
                        "switches them."),
            model=Gtk.StringList.new(labels))
        self.switch_row.set_selected(SWITCHES.index(self.prefs["switch"]))
        self.switch_row.set_sensitive("," in layouts)
        self.switch_row.connect("notify::selected", lambda r, _p: self._set(
            "switch", SWITCHES[r.get_selected()]))
        gk.add(self.switch_row)
        self.add(gk)

        # --- typing
        gt = Adw.PreferencesGroup(title=tr("Typing"),
                                  description=tr("What happens when you hold a key down."))
        gt.add(scale_row(tr("Delay before repeating"), tr("Short on the left, long on the right"),
                         150, 1000, 25, self.prefs["repeat_delay"],
                         lambda v: self._set("repeat_delay", int(v))))
        gt.add(scale_row(tr("Repeat speed"), tr("Slow on the left, fast on the right"),
                         5, 60, 1, self.prefs["repeat_rate"],
                         lambda v: self._set("repeat_rate", int(v))))
        gt.add(Adw.EntryRow(title=tr("Try it here")))
        self.add(gt)

        # --- mouse
        gm = Adw.PreferencesGroup(title=tr("Mouse"))
        gm.add(scale_row(tr("Pointer speed"), tr("Slow on the left, fast on the right"),
                         -1.0, 1.0, 0.05, self.prefs["sensitivity"],
                         lambda v: self._set("sensitivity", round(v, 2)), marks=((0.0, None),)))
        gm.add(self._switch(tr("Natural scrolling"),
                            tr("The content follows the wheel, like on a phone screen"),
                            "natural_scroll"))
        self.add(gm)

        # --- touchpad
        gp = Adw.PreferencesGroup(
            title=tr("Touchpad"),
            description="" if has_touchpad() else tr("No touchpad found on this computer: these "
                                                     "settings apply when one is connected."))
        gp.add(self._switch(tr("Tap to click"),
                            tr("A tap clicks; with two fingers it is a right click"),
                            "tap_to_click"))
        gp.add(self._switch(tr("Natural scrolling"),
                            tr("The content follows your fingers, like on a phone screen"),
                            "touchpad_natural_scroll"))
        gp.add(self._switch(tr("Disable while typing"),
                            tr("No accidental clicks with the palm of the hand"),
                            "disable_while_typing"))
        self.add(gp)

        reset = Adw.PreferencesGroup()
        r = Adw.ActionRow(title=tr("Restore the defaults"), activatable=True)
        r.add_prefix(Gtk.Image(icon_name="view-refresh-symbolic"))
        r.connect("activated", lambda *_: self._reset())
        reset.add(r)
        self.add(reset)

    def _switch(self, title, subtitle, key):
        row = Adw.SwitchRow(title=title, subtitle=subtitle, active=self.prefs[key])
        row.connect("notify::active", lambda r, _p: self._set(key, r.get_active()))
        return row

    def _open_language(self):
        root = self.get_root()
        if hasattr(root, "show"):
            root.show("language")

    def _set(self, key, value):
        if self.prefs.get(key) == value:
            return
        self.prefs[key] = value
        # sliders send many values while they move: apply once they stop
        if self._timer:
            GLib.source_remove(self._timer)
        self._timer = GLib.timeout_add(400, self._apply)

    def _apply(self):
        self._timer = None
        try:
            save(self.prefs)
        except OSError as e:
            print("zeta-settings: keyboard and mouse not saved: %s" % e)
        code = "hl.config(%s)" % lua_literal(hypr_table(self.prefs))
        layouts, options = session_layouts()
        if "," in layouts and "grp:" in options:
            code += "; hl.config({ input = { kb_options = %s } })" % lua_literal(
                re.sub(r"grp:[a-z_]+", self.prefs["switch"], options))
        hypr_eval(code)
        return False

    def _reset(self):
        self.prefs = dict(DEFAULTS)
        self._apply()
        root = self.get_root()
        if hasattr(root, "reload_page"):
            root.reload_page("keyboard")
