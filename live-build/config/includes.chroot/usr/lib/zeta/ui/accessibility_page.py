"""Settings > Accessibility.

Screen reader (Orca), larger text, high contrast, a larger pointer, zoom
and fewer animations. Every choice stays after logging in again:

- text size, high contrast and the screen reader are the standard desktop
  keys (org.gnome.desktop.interface / a11y), kept by dconf and read by the
  GTK and libadwaita apps;
- pointer size and animations belong to zeta-appearance (the same values
  as Settings > Appearance: one place, never two copies);
- zoom and the thicker window borders of high contrast are written to
  ~/.config/hypr/zeta_accessibility.lua, read by hyprland.lua at start
  ({ config = <hl.config table> }), and applied at once with hyprctl eval;
- the screen reader is started at login by zeta-session-services when it
  is on; Super + Alt + S turns it on or off from anywhere.
"""
import json
import os
import shutil

import gi
gi.require_version("Gtk", "4.0")
gi.require_version("Adw", "1")
from gi.repository import Adw, GLib, Gtk  # noqa: E402

from i18n import tr  # noqa: E402
from ui.page_tools import (bg, gsettings, hypr_eval, lua_literal, run_quiet, scale_row,  # noqa: E402
                           spawn, toast, write_if_changed)

PREFS = os.path.expanduser("~/.config/zeta/accessibility.json")
LUA = os.path.expanduser("~/.config/hypr/zeta_accessibility.lua")
APPEARANCE = os.path.expanduser("~/.config/zeta")
TEXT_SCALES = [1.0, 1.25, 1.5]
CURSOR_SIZES = [24, 32, 40, 48]
DEFAULTS = {"zoom": 1.0, "high_contrast": False}


def load():
    prefs = dict(DEFAULTS)
    try:
        with open(PREFS, encoding="utf-8") as f:
            saved = json.load(f)
        if isinstance(saved, dict):
            z = float(saved.get("zoom", 1.0))
            prefs["zoom"] = min(4.0, max(1.0, z))
            prefs["high_contrast"] = saved.get("high_contrast") is True
    except (OSError, ValueError, TypeError):
        pass
    return prefs


def hypr_table(prefs):
    table = {"cursor": {"zoom_factor": round(float(prefs["zoom"]), 2)}}
    if prefs["high_contrast"]:
        # window borders three times thicker, easier to see
        table["general"] = {"border_size": 3}
    return table


def lua_text(prefs):
    return ("-- Settings > Accessibility (generated by ZETA RAYS Settings: changes made\n"
            "-- here are overwritten). Read by hyprland.lua.\n"
            "return {\n    config = %s,\n}\n" % lua_literal(hypr_table(prefs)))


def save(prefs):
    os.makedirs(os.path.dirname(PREFS), exist_ok=True)
    with open(PREFS + ".tmp", "w", encoding="utf-8") as f:
        json.dump(prefs, f)
    os.replace(PREFS + ".tmp", PREFS)
    write_if_changed(LUA, lua_text(prefs))


def appearance_value(key, default):
    """A value of zeta-appearance (one file per key in ~/.config/zeta)."""
    try:
        with open(os.path.join(APPEARANCE, key), encoding="utf-8") as f:
            return f.read().strip() or default
    except OSError:
        return default


def _nearest(values, v):
    return min(range(len(values)), key=lambda i: abs(values[i] - v))


class AccessibilityPage(Adw.PreferencesPage):
    def __init__(self):
        super().__init__()
        self.prefs = load()
        self._timer = None
        self.iface = gsettings("org.gnome.desktop.interface")
        self.a11y_apps = gsettings("org.gnome.desktop.a11y.applications")
        self.a11y_iface = gsettings("org.gnome.desktop.a11y.interface")

        # --- seeing
        gv = Adw.PreferencesGroup(title=tr("Vision"))
        self.reader = Adw.SwitchRow(
            title=tr("Screen reader"),
            subtitle=tr("Reads aloud what is on the screen. Super + Alt + S turns it on or off."))
        if shutil.which("orca") is None or self.a11y_apps is None:
            self.reader.set_subtitle(tr("Not installed"))
            self.reader.set_sensitive(False)
        else:
            self.reader.set_active(self.a11y_apps.get_boolean("screen-reader-enabled"))
        self.reader.connect("notify::active", self._on_reader)
        gv.add(self.reader)

        self.text = Adw.ComboRow(title=tr("Text size"),
                                 subtitle=tr("Text in the apps and in the system windows"),
                                 model=Gtk.StringList.new([tr("Default"), tr("Large"), tr("Larger")]))
        if self.iface is not None:
            self.text.set_selected(_nearest(TEXT_SCALES, self.iface.get_double("text-scaling-factor")))
        else:
            self.text.set_sensitive(False)
        self.text.connect("notify::selected", self._on_text)
        gv.add(self.text)

        self.contrast = Adw.SwitchRow(
            title=tr("High contrast"),
            subtitle=tr("Stronger colors and borders in the apps, thicker window borders"),
            active=self.prefs["high_contrast"])
        self.contrast.connect("notify::active", self._on_contrast)
        gv.add(self.contrast)

        try:
            cursor = int(appearance_value("cursor-size", "24"))
        except ValueError:
            cursor = 24
        self.pointer = Adw.ComboRow(title=tr("Pointer size"),
                                    model=Gtk.StringList.new([tr("Default"), tr("Large"),
                                                              tr("Larger"), tr("Largest")]))
        self.pointer.set_selected(_nearest(CURSOR_SIZES, cursor))
        self.pointer.connect("notify::selected", lambda r, _p: self._appearance(
            "cursor-size", str(CURSOR_SIZES[r.get_selected()])))
        gv.add(self.pointer)

        self.zoom = scale_row(
            tr("Zoom"),
            tr("Magnifies around the pointer. Super + plus and Super + minus zoom in and out, "
               "Super + 0 goes back to normal."),
            1.0, 4.0, 0.25, self.prefs["zoom"], self._on_zoom, marks=((1.0, None), (2.0, None)))
        gv.add(self.zoom)
        self.add(gv)

        # --- movement
        gm = Adw.PreferencesGroup(title=tr("Motion"))
        self.calm = Adw.SwitchRow(
            title=tr("Reduce motion"),
            subtitle=tr("Windows and panels appear without animations"),
            active=appearance_value("animations", "1") == "0")
        self.calm.connect("notify::active", lambda r, _p: self._appearance(
            "animations", "0" if r.get_active() else "1"))
        gm.add(self.calm)
        self.add(gm)

    # ------------------------------------------------------------ actions
    def _on_reader(self, row, _p):
        if self.a11y_apps is None:
            return
        on = row.get_active()
        if on == self.a11y_apps.get_boolean("screen-reader-enabled"):
            return
        # zeta-screen-reader keeps the key and the running Orca together
        spawn("zeta-screen-reader", "on" if on else "off")

    def _on_text(self, row, _p):
        i = row.get_selected()
        if self.iface is None or not 0 <= i < len(TEXT_SCALES):
            return
        self.iface.set_double("text-scaling-factor", TEXT_SCALES[i])

    def _on_contrast(self, row, _p):
        on = row.get_active()
        self.prefs["high_contrast"] = on
        if self.a11y_iface is not None:
            self.a11y_iface.set_boolean("high-contrast", on)
        self._save_soon()

    def _on_zoom(self, value):
        self.prefs["zoom"] = round(value * 4) / 4
        self._save_soon()

    def _save_soon(self):
        if self._timer:
            GLib.source_remove(self._timer)
        self._timer = GLib.timeout_add(300, self._apply)

    def _apply(self):
        self._timer = None
        try:
            save(self.prefs)
        except OSError as e:
            print("zeta-settings: accessibility not saved: %s" % e)
        zoom = lua_literal(round(float(self.prefs["zoom"]), 2))
        hypr_eval("zeta_zoom_level = %s; hl.config({ cursor = { zoom_factor = %s }, "
                  "general = { border_size = %d } })"
                  % (zoom, zoom, 3 if self.prefs["high_contrast"] else 1))
        return False

    def _appearance(self, key, value):
        def done(ok):
            if ok is not True:
                toast(self, tr("Could not apply “{setting}”").format(setting=key))
            root = self.get_root()
            if hasattr(root, "forget_page"):
                # Appearance shows the same values: it is rebuilt when opened again
                root.forget_page("appearance")
        bg(lambda: run_quiet(["zeta-appearance", "set", key, value], timeout=60), done)
