"""ZETA RAYS — light or dark theme, shared by all ZETA RAYS apps.

The actual colors live in ~/.config/zeta/colors.css, regenerated by zeta-accent
whenever the accent color or the theme changes. Here we load them and expose
them as @surface, @ink, @line… so every app follows the theme without
hard-coded colors.
"""
import os

THEME_FILE = os.path.expanduser("~/.config/zeta/theme")
COLORS_FILE = os.path.expanduser("~/.config/zeta/colors.css")

FALLBACK = """
@define-color accent #3A8DFF;
@define-color accent_ink #FFFFFF;
@define-color accent_soft rgba(58,141,255,0.14);
@define-color accent_line rgba(58,141,255,0.35);
@define-color surface rgba(18,18,20,0.94);
@define-color surface_2 rgba(255,255,255,0.04);
@define-color ink #EDEDEA;
@define-color ink_2 #C8C8CC;
@define-color ink_dim #8A8A8E;
@define-color line rgba(255,255,255,0.08);
@define-color hover rgba(255,255,255,0.07);
@define-color hover_2 rgba(255,255,255,0.14);
@define-color glass rgba(18,18,20,0.78);
@define-color scrim rgba(0,0,0,0.45);
@define-color scrim_strong rgba(0,0,0,0.74);
"""


def is_light():
    try:
        with open(THEME_FILE) as f:
            return f.read().strip() == "light"
    except OSError:
        return False


def colors_css():
    try:
        with open(COLORS_FILE) as f:
            css = f.read()
        if "@define-color surface" in css:      # an old-version file lacks it
            return css
    except OSError:
        pass
    return FALLBACK


# The color provider is kept aside: reload() reloads the updated file into
# it instead of stacking another one on top. Adding one on every theme change
# would pile them up for the whole lifetime of the window.
_base = None


def _schema(font="", icons=""):
    """Light or dark for GTK and libadwaita, plus font and icons if requested."""
    from gi.repository import Gtk
    use_adw = False
    try:
        import gi
        gi.require_version("Adw", "1")
        from gi.repository import Adw
        Adw.StyleManager.get_default().set_color_scheme(
            Adw.ColorScheme.FORCE_LIGHT if is_light() else Adw.ColorScheme.FORCE_DARK)
        use_adw = True
    except (ImportError, ValueError):
        pass
    st = Gtk.Settings.get_default()
    if st is not None:
        # With libadwaita the scheme is chosen ONLY through AdwStyleManager:
        # also setting the GTK property triggers a warning and achieves nothing.
        if not use_adw:
            st.set_property("gtk-application-prefer-dark-theme", not is_light())
        if font:
            st.set_property("gtk-font-name", font)
        if icons:
            st.set_property("gtk-icon-theme-name", icons)


def reload():
    """Reload theme and colors while the window is open (after
    "zeta-appearance toggle-theme").

    Without this, a user changing the theme from the control center or from
    Settings saw the whole desktop change except the very window they had just
    changed it from, which kept the old colors until it was reopened.
    """
    if _base is None:
        return
    _schema()
    _base.load_from_string(colors_css())


def apply(app_css="", font="Roboto 10", icons="zeta"):
    """Load the theme colors and then the app's style. Call it from do_activate."""
    global _base
    from gi.repository import Gdk, Gtk
    display = Gdk.Display.get_default()
    _schema(font, icons)
    _base = Gtk.CssProvider()
    _base.load_from_string(colors_css())
    Gtk.StyleContext.add_provider_for_display(display, _base,
                                              Gtk.STYLE_PROVIDER_PRIORITY_APPLICATION)
    if app_css:
        prov = Gtk.CssProvider()
        prov.load_from_string(app_css)
        Gtk.StyleContext.add_provider_for_display(display, prov,
                                                  Gtk.STYLE_PROVIDER_PRIORITY_APPLICATION + 1)
