"""Settings > Windows & Multitasking.

- Remember window size and position: hyprland.lua (WINDOW MEMORY) reopens a
  program's main window where it was last closed. Written to
  ~/.config/hypr/zeta_windows.lua ({ memory = ..., config = ... }), read at
  start, and applied at once with hyprctl eval.
- Focus follows the pointer: Hyprland's input.follow_mouse.
- Windows always reachable: the window guard is always on (it cannot be
  turned off: a window out of reach is never what anyone wants); here there
  is the button that brings every window back at once (zeta-windows
  recover, the same as Super + Shift + W).
"""
import json
import os

import gi
gi.require_version("Gtk", "4.0")
gi.require_version("Adw", "1")
from gi.repository import Adw, Gtk  # noqa: E402

from i18n import tr  # noqa: E402
from ui.page_tools import confirm, hypr_eval, lua_literal, spawn, toast, write_if_changed  # noqa: E402

PREFS = os.path.expanduser("~/.config/zeta/windows.json")
LUA = os.path.expanduser("~/.config/hypr/zeta_windows.lua")
DEFAULTS = {"memory": True, "follow_mouse": True}


def load():
    prefs = dict(DEFAULTS)
    try:
        with open(PREFS, encoding="utf-8") as f:
            saved = json.load(f)
        for k in DEFAULTS:
            if isinstance(saved.get(k), bool):
                prefs[k] = saved[k]
    except (OSError, ValueError, AttributeError):
        pass
    return prefs


def lua_text(prefs):
    table = {"input": {"follow_mouse": 1 if prefs["follow_mouse"] else 0}}
    return ("-- Settings > Windows & Multitasking (generated by ZETA RAYS Settings:\n"
            "-- changes made here are overwritten). Read by hyprland.lua.\n"
            "return {\n    memory = %s,\n    config = %s,\n}\n"
            % ("true" if prefs["memory"] else "false", lua_literal(table)))


def save(prefs):
    os.makedirs(os.path.dirname(PREFS), exist_ok=True)
    with open(PREFS + ".tmp", "w", encoding="utf-8") as f:
        json.dump(prefs, f)
    os.replace(PREFS + ".tmp", PREFS)
    write_if_changed(LUA, lua_text(prefs))


class WindowsPage(Adw.PreferencesPage):
    def __init__(self):
        super().__init__()
        self.prefs = load()

        g = Adw.PreferencesGroup(title=tr("Windows"))
        mem = Adw.SwitchRow(
            title=tr("Remember size and position"),
            subtitle=tr("Each program opens where you last closed it, on the same display"),
            active=self.prefs["memory"])
        mem.connect("notify::active", self._on_memory)
        g.add(mem)
        forget = Adw.ActionRow(title=tr("Forget saved positions"),
                               subtitle=tr("Programs open centered again, at their usual size"))
        b = Gtk.Button(label=tr("Forget"), valign=Gtk.Align.CENTER)
        b.connect("clicked", self._on_forget)
        forget.add_suffix(b)
        g.add(forget)
        follow = Adw.SwitchRow(
            title=tr("Focus follows the pointer"),
            subtitle=tr("The window under the pointer receives the keyboard. Off: click a window to use it"),
            active=self.prefs["follow_mouse"])
        follow.connect("notify::active", self._on_follow)
        g.add(follow)
        self.add(g)

        g = Adw.PreferencesGroup(
            title=tr("Always reachable"),
            description=tr("No window can stay outside the screen or hide its title bar: after a "
                           "resolution change, a display unplugged or a program that moves itself, "
                           "windows come back inside on their own."))
        rec = Adw.ActionRow(title=tr("Bring every window back now"),
                            subtitle=tr("Also with Super + Shift + W, from anywhere"))
        b = Gtk.Button(label=tr("Bring back"), valign=Gtk.Align.CENTER)
        b.connect("clicked", lambda *_: (spawn("zeta-windows", "recover"),
                                         toast(self, tr("Windows brought back inside the screen"))))
        rec.add_suffix(b)
        g.add(rec)
        self.add(g)

        g = Adw.PreferencesGroup(title=tr("Layouts and shortcuts"))
        for title, keys in ((tr("Snap layouts (halves, thirds, quarters)"), "Super + Z"),
                            (tr("Left or right half of the screen"), "Super + Shift + ← / →"),
                            (tr("Maximize or restore"), "Super + Shift + ↑ / ↓"),
                            (tr("Switch between open apps"), "Ctrl + Tab"),
                            (tr("Close a program that is not responding"), "Ctrl + Alt + Esc")):
            row = Adw.ActionRow(title=title)
            row.add_suffix(Gtk.Label(label=keys, css_classes=["dim-label"]))
            g.add(row)
        self.add(g)

    def _store(self):
        try:
            save(self.prefs)
        except OSError as e:
            toast(self, tr("Not saved: {error}").format(error=e))

    def _on_memory(self, row, _p):
        self.prefs["memory"] = row.get_active()
        self._store()
        hypr_eval("zeta_window_memory = %s" % ("true" if self.prefs["memory"] else "false"))

    def _on_follow(self, row, _p):
        self.prefs["follow_mouse"] = row.get_active()
        self._store()
        hypr_eval("hl.config({ input = { follow_mouse = %d } })" % (1 if self.prefs["follow_mouse"] else 0))

    def _on_forget(self, *_a):
        confirm(self, tr("Forget the saved positions?"),
                tr("Every program will open centered again, at its usual size."),
                tr("Forget"), lambda: (hypr_eval("zeta_memory_forget()"),
                                       toast(self, tr("Saved positions forgotten"))))
