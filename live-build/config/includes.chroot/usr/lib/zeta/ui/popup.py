# The two providers are kept at hand: reload() loads the updated file back
# into them instead of stacking new ones on top, which would have piled up on
# every theme change for the whole life of the panel.
_colors = None
_style = None


def _read_colors(provider, default=None):
    path = os.path.expanduser("~/.config/zeta/colors.css")
    if os.path.exists(path):
        provider.load_from_path(path)
    else:
        provider.load_from_string(default or DEFAULT_COLORS)


def _theme_stamp():
    stamp = []
    for name in ("colors.css", "theme"):
        try:
            stamp.append(os.stat(os.path.expanduser("~/.config/zeta/" + name)).st_mtime_ns)
        except OSError:
            stamp.append(0)
    return tuple(stamp)


_loaded_stamp = None


def follow_theme(provider=None, default=None):
    """Resident panels stay in memory for the whole session: before one is
    shown, its colors are reloaded if the theme or the accent color changed
    since they were loaded (otherwise it kept the colors of the login)."""
    global _loaded_stamp
    stamp = _theme_stamp()
    if stamp == _loaded_stamp:
        return
    _loaded_stamp = stamp
    from gi.repository import Gtk
    try:
        Gtk.Settings.get_default().set_property("gtk-application-prefer-dark-theme", not _is_light())
    except TypeError:
        pass
    provider = provider or _colors
    if provider is not None:
        _read_colors(provider, default)


def _is_light():
    try:
        return open(os.path.expanduser("~/.config/zeta/theme")).read().strip() == "light"
    except OSError:
        return False


def load_css(extra=""):
    global _colors, _style
    from gi.repository import Gdk, Gtk
    settings = Gtk.Settings.get_default()
    # The panels are plain GTK4 (no libadwaita): here the property is needed.
    try:
        settings.set_property("gtk-application-prefer-dark-theme", not _is_light())
    except TypeError:
        pass
    settings.set_property("gtk-icon-theme-name", "zeta")
    settings.set_property("gtk-font-name", "Roboto 10")
    display = Gdk.Display.get_default()
    _colors = Gtk.CssProvider()
    _read_colors(_colors)
    global _loaded_stamp
    _loaded_stamp = _theme_stamp()
    _style = Gtk.CssProvider()
    _style.load_from_string(BASE_CSS + extra)
    Gtk.StyleContext.add_provider_for_display(display, _colors, Gtk.STYLE_PROVIDER_PRIORITY_APPLICATION)
    Gtk.StyleContext.add_provider_for_display(display, _style, Gtk.STYLE_PROVIDER_PRIORITY_APPLICATION + 1)


def reload():
    """Reload the colors while the panel is open, after a theme change.

    Needed by panels that change the theme themselves (the control center):
    without it, the whole desktop changed while the very panel the button was
    pressed in kept the old colors.
    """
    if _colors is None:
        return
    from gi.repository import Gtk
    settings = Gtk.Settings.get_default()
    try:
        settings.set_property("gtk-application-prefer-dark-theme", not _is_light())
    except TypeError:
        pass
    _read_colors(_colors)


def make_overlay(window, namespace, keyboard=True):
    """Full-screen, transparent window above everything (layer shell)."""
    try:
        import gi
        gi.require_version("Gtk4LayerShell", "1.0")
        from gi.repository import Gtk4LayerShell as LS
    except (ValueError, ImportError):
        LS = None
    window.add_css_class("zeta-overlay")
    if LS and LS.is_supported():
        LS.init_for_window(window)
        LS.set_namespace(window, namespace)
        LS.set_layer(window, LS.Layer.OVERLAY)
        LS.set_keyboard_mode(window, LS.KeyboardMode.EXCLUSIVE if keyboard else LS.KeyboardMode.NONE)
        LS.set_exclusive_zone(window, -1)
        for edge in (LS.Edge.TOP, LS.Edge.BOTTOM, LS.Edge.LEFT, LS.Edge.RIGHT):
            LS.set_anchor(window, edge, True)
    else:
        window.fullscreen()


def _cursor_monitor():
    """(cursor x relative to its monitor, logical monitor width, monitor
    name). With several monitors "hyprctl cursorpos" returns global
    coordinates: without subtracting the monitor position a menu ended up
    off screen."""
    import json
    import subprocess
    try:
        cur = json.loads(subprocess.run(["hyprctl", "-j", "cursorpos"], capture_output=True,
                                        text=True, timeout=2).stdout)
        mons = json.loads(subprocess.run(["hyprctl", "-j", "monitors"], capture_output=True,
                                         text=True, timeout=2).stdout)
    except (OSError, subprocess.SubprocessError, ValueError):
        return 0, None, None
    cx, cy = cur.get("x", 0), cur.get("y", 0)
    chosen = None
    for m in mons:
        scala = m.get("scale") or 1
        w, h = m.get("width", 0) / scala, m.get("height", 0) / scala
        if m.get("transform", 0) % 2:
            w, h = h, w
        if m.get("x", 0) <= cx < m.get("x", 0) + w and m.get("y", 0) <= cy < m.get("y", 0) + h:
            chosen = (m, w)
            break
        if chosen is None and m.get("focused"):
            chosen = (m, w)
    if chosen is None:
        return cx, None, None
    m, w = chosen
    return cx - m.get("x", 0), w, m.get("name")


def menu_at_cursor(window, card, width=220):
    """A bar menu (Dock, minimized windows, Mail) under the cursor, on the
    cursor's monitor and ALWAYS fully inside the screen: near the right edge
    it moves left instead of spilling over. Must be called after
    make_overlay."""
    x, mon_width, connector = _cursor_monitor()
    card.set_size_request(width, -1)
    if mon_width:
        start = min(x - width / 2, mon_width - width - 8)
    else:
        start = x - width / 2
    card.set_margin_start(int(max(8, start)))
    card.set_margin_end(8)
    if connector:
        try:
            import gi
            gi.require_version("Gtk4LayerShell", "1.0")
            from gi.repository import Gdk, Gtk4LayerShell as LS
            monitors = Gdk.Display.get_default().get_monitors()
            for i in range(monitors.get_n_items()):
                gm = monitors.get_item(i)
                if gm.get_connector() == connector:
                    LS.set_monitor(window, gm)
                    break
        except (ValueError, ImportError, AttributeError):
            pass


def close_on_outside(window, card, on_close):
    """Esc or a click outside the box closes the panel."""
    from gi.repository import Gdk, Gtk
    keys = Gtk.EventControllerKey(propagation_phase=Gtk.PropagationPhase.CAPTURE)
    keys.connect("key-pressed", lambda _c, kv, _k, _s: (on_close(), True)[1]
                 if kv == Gdk.KEY_Escape else False)
    window.add_controller(keys)
    click = Gtk.GestureClick()

    def released(_g, _n, x, y):
        w = window.pick(x, y, Gtk.PickFlags.DEFAULT)
        while w is not None:
            if w is card:
                return
            w = w.get_parent()
        on_close()
    click.connect("released", released)
    window.add_controller(click)
