"""ZETA RAYS — shared base for the overlay panels (control center, power).

- gtk4-layer-shell must be loaded before libwayland: the process re-executes
  itself with LD_PRELOAD. That variable must NOT reach programs launched from
  the panel (GTK3 apps would load GTK4 and quit at once): clean_env() removes
  it as soon as the panel has started.
- Accent colors shared with the launcher (~/.config/zeta/colors.css).
"""
import glob
import os
import sys

MARK = "ZETA_LAYER_PRELOADED"


def preload_layer_shell():
    if MARK in os.environ:
        return
    libs = glob.glob("/usr/lib/*/libgtk4-layer-shell.so.0")
    if not libs:
        return
    env = dict(os.environ, **{MARK: "1"})
    env["LD_PRELOAD"] = (libs[0] + " " + os.environ.get("LD_PRELOAD", "")).strip()
    os.execve(sys.executable, [sys.executable] + sys.argv, env)


# Resident panels: "ZETA_PANEL_HIDDEN=1 zeta-power-menu" starts it and
# keeps it ready in memory without showing it (the session does this); then
# "zeta-panel power" shows it instantly (the "show" action).
HIDDEN_ENV = "ZETA_PANEL_HIDDEN"


def started_hidden():
    """True only once, for the process started by the session."""
    return os.environ.pop(HIDDEN_ENV, None) == "1"


def show_action(app, toggle):
    """Add the "show" action to the app (used by zeta-panel)."""
    from gi.repository import Gio
    a = Gio.SimpleAction.new("show", None)
    a.connect("activate", lambda *_: (follow_theme(), toggle()))
    app.add_action(a)


def clean_env():
    """Call after GTK has started: child processes start with the normal environment."""
    pre = os.environ.get("LD_PRELOAD", "")
    kept = " ".join(p for p in pre.split() if "gtk4-layer-shell" not in p)
    if kept:
        os.environ["LD_PRELOAD"] = kept
    else:
        os.environ.pop("LD_PRELOAD", None)
    os.environ.pop(MARK, None)


