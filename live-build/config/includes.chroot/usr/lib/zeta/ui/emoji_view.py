"""ZETA RAYS: emoji picker (Super+period), a view of zeta-clipboard.

Grid of emoji by category with search by English name. The most recently
used come first. The list is /usr/share/zeta/emoji.json (generated by
tools/gen-emoji-data.py from Unicode's emoji-test.txt).

The grid is a Gtk.GridView: only the visible cells exist as widgets, so the
1,900 emoji do not slow down opening or searching.
"""
import json
import os

import gi
gi.require_version("Gtk", "4.0")
from gi.repository import Gdk, Gtk, Pango  # noqa: E402

from i18n import tr  # noqa: E402

DATA = "/usr/share/zeta/emoji.json"
RECENT = os.path.expanduser("~/.local/share/zeta/emoji-recent")
RECENT_MAX = 32
COLUMNS = 8

# Group names in emoji-test.txt -> (shown name, symbol of its button)
GROUPS = {
    "Smileys & Emotion": (tr("Smileys & Emotion"), "😀"),
    "People & Body": (tr("People & Body"), "👋"),
    "Animals & Nature": (tr("Animals & Nature"), "🐻"),
    "Food & Drink": (tr("Food & Drink"), "🍔"),
    "Travel & Places": (tr("Travel & Places"), "🚗"),
    "Activities": (tr("Activities"), "⚽"),
    "Objects": (tr("Objects"), "💡"),
    "Symbols": (tr("Symbols"), "❤️"),
    "Flags": (tr("Flags"), "🏳️"),
}
RECENT_KEY = "recent"

CSS = """
.emoji-cell { font-size: 22px; min-width: 40px; min-height: 40px; }
gridview.emoji-grid { background: none; }
gridview.emoji-grid > child { border-radius: 10px; padding: 0; }
gridview.emoji-grid > child:hover { background: @hover; }
gridview.emoji-grid > child:focus { background: @accent_soft; outline: none; }
button.emoji-cat { min-width: 32px; min-height: 32px; padding: 0; border-radius: 10px;
                   background: none; border: none; box-shadow: none; font-size: 16px; }
button.emoji-cat:hover { background: @hover; }
button.emoji-cat.on { background: @accent_soft; }
.emoji-name { font-size: 12px; color: @ink_dim; }
"""


def load_emoji(path=DATA):
    """[(emoji, name, group key)] in the file's order."""
    items = []
    try:
        with open(path, encoding="utf-8") as f:
            data = json.load(f)
    except (OSError, ValueError):
        return items
    for group, block in data.get("groups", []):
        for line in block.split("\n"):
            emoji, _sp, name = line.partition(" ")
            if emoji:
                items.append((emoji, name, group))
    return items


def search(items, query, recent=(), stem=True):
    """Indexes of the emoji whose name contains every word of the query.
    Recently used first, then whole words ("heart" finds "red heart" before
    "smiling face with hearts"), then word starts, then anywhere; shorter
    names first."""
    words = query.lower().split()
    if not words:
        return []
    rank = {e: i for i, e in enumerate(recent)}
    found = []
    for i, (emoji, name, _g) in enumerate(items):
        low = name.lower()
        if all(w in low for w in words):
            parts = low.replace(":", " ").replace("-", " ").split()
            if " ".join(parts) == " ".join(words):
                quality = 0
            elif all(w in parts for w in words):
                quality = 1
            elif all(any(p.startswith(w) for p in parts) for w in words):
                quality = 2
            else:
                quality = 3
            # shorter names are closer to what was typed
            found.append((0 if emoji in rank else 1, rank.get(emoji, 0), quality, len(parts), i))
    found.sort()
    result = [f[-1] for f in found]
    # few results: try the stem too ("smile" also finds "smiling face")
    stems = [w[:-1] if len(w) >= 5 else w for w in words]
    if stem and len(result) < 8 and stems != words:
        seen = set(result)
        result += [i for i in search(items, " ".join(stems), recent, stem=False) if i not in seen]
    return result


def load_recent():
    try:
        with open(RECENT, encoding="utf-8") as f:
            return [line for line in f.read().split("\n") if line][:RECENT_MAX]
    except OSError:
        return []


def save_recent(recent):
    try:
        os.makedirs(os.path.dirname(RECENT), exist_ok=True)
        with open(RECENT, "w", encoding="utf-8") as f:
            f.write("\n".join(recent[:RECENT_MAX]) + "\n")
    except OSError:
        pass


class EmojiView(Gtk.Box):
    """on_pick(emoji) is called with the chosen emoji."""

    def __init__(self, on_pick):
        super().__init__(orientation=Gtk.Orientation.VERTICAL, spacing=10)
        self.on_pick = on_pick
        self.items = load_emoji()
        self.index = {e: i for i, (e, _n, _g) in enumerate(self.items)}
        self.recent = [e for e in load_recent() if e in self.index]
        self.group = None

        self.search = Gtk.SearchEntry(placeholder_text=tr("Search emoji"), hexpand=True)
        self.search.add_css_class("zeta-entry")
        self.search.set_search_delay(80)
        self.search.connect("search-changed", lambda *_: self.refresh())
        self.search.connect("activate", lambda *_: self.pick_first())
        # capture: the entry's own text field would otherwise take the Down key
        keys = Gtk.EventControllerKey(propagation_phase=Gtk.PropagationPhase.CAPTURE)
        keys.connect("key-pressed", self._search_key)
        self.search.add_controller(keys)
        self.append(self.search)

        self.cats = Gtk.Box(spacing=2, halign=Gtk.Align.CENTER)
        self.cat_buttons = {}
        for key, symbol, title in [(RECENT_KEY, "🕘", tr("Recently used"))] + \
                [(g, GROUPS[g][1], GROUPS[g][0]) for g in GROUPS]:
            b = Gtk.Button(label=symbol, css_classes=["emoji-cat"], tooltip_text=title)
            b.connect("clicked", lambda _b, k=key: self.show_group(k))
            self.cats.append(b)
            self.cat_buttons[key] = b
        self.append(self.cats)

        self.model = Gtk.StringList()
        factory = Gtk.SignalListItemFactory()
        factory.connect("setup", self._setup)
        factory.connect("bind", self._bind)
        self.grid = Gtk.GridView(model=Gtk.NoSelection(model=self.model), factory=factory,
                                 min_columns=COLUMNS, max_columns=COLUMNS,
                                 single_click_activate=True, css_classes=["emoji-grid"])
        self.grid.connect("activate", lambda _g, pos: self.pick_position(pos))
        self.scroll = Gtk.ScrolledWindow(vexpand=True, hscrollbar_policy=Gtk.PolicyType.NEVER,
                                         child=self.grid)
        self.stack = Gtk.Stack()
        self.stack.add_named(self.scroll, "grid")
        self.stack.add_named(Gtk.Label(label=tr("No emoji found"), css_classes=["zeta-dim"],
                                       vexpand=True), "empty")
        self.append(self.stack)
        self.name = Gtk.Label(xalign=0, css_classes=["emoji-name"],
                              ellipsize=Pango.EllipsizeMode.END,
                              label=tr("Click an emoji to insert it"))
        self.append(self.name)

    # --- grid cells ---
    def _setup(self, _factory, item):
        item.set_child(Gtk.Label(css_classes=["emoji-cell"]))

    def _bind(self, _factory, item):
        i = int(item.get_item().get_string())
        emoji, name, _g = self.items[i]
        label = item.get_child()
        label.set_text(emoji)
        label.set_tooltip_text(name)

    # --- content ---
    def prepare(self):
        """Every time the panel opens: empty search, recent emoji first."""
        self.search.set_text("")
        self.show_group(RECENT_KEY if self.recent else "Smileys & Emotion")
        self.cat_buttons[RECENT_KEY].set_visible(bool(self.recent))

    def focus(self):
        self.search.grab_focus()

    def show_group(self, key):
        self.group = key
        for k, b in self.cat_buttons.items():
            if k == key:
                b.add_css_class("on")
            else:
                b.remove_css_class("on")
        if self.search.get_text():
            self.search.set_text("")      # search-changed refreshes
        self.refresh()

    def refresh(self):
        query = self.search.get_text().strip()
        if query:
            found = search(self.items, query, self.recent)
            title = None
        elif self.group == RECENT_KEY:
            found = [self.index[e] for e in self.recent]
            title = tr("Recently used")
        else:
            found = [i for i, it in enumerate(self.items) if it[2] == self.group]
            title = GROUPS.get(self.group, ("", ""))[0]
        self.model.splice(0, self.model.get_n_items(), [str(i) for i in found])
        self.stack.set_visible_child_name("grid" if found else "empty")
        self.name.set_text(title or tr("Click an emoji to insert it"))
        self.scroll.get_vadjustment().set_value(0)

    def _search_key(self, _ctl, keyval, _code, _state):
        if keyval == Gdk.KEY_Down and self.model.get_n_items():
            self.grid.scroll_to(0, Gtk.ListScrollFlags.FOCUS, None)
            return True
        return False

    def pick_first(self):
        if self.model.get_n_items():
            self.pick_position(0)

    def pick_position(self, pos):
        item = self.model.get_item(pos)
        if item is None:
            return
        emoji = self.items[int(item.get_string())][0]
        self.recent = [emoji] + [e for e in self.recent if e != emoji]
        self.recent = self.recent[:RECENT_MAX]
        save_recent(self.recent)
        self.on_pick(emoji)
